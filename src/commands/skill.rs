use super::{help, is_command};
use crate::config::home_dir;
use crate::json::Object;
use crate::logger;
use std::path::{Path, PathBuf};

const SKILL_NAME: &str = "jsonr";
const SKILL_CONTENT: &str = include_str!("../templates/SKILL.md");
const AGENT_INSTRUCTIONS: &str = include_str!("../templates/agent-instructions.txt");
const SKILL_TARGETS: &[(&str, &str)] = &[
    (".agents/skills", "Codex, Cursor"),
    (".claude/skills", "Claude Code, Cursor"),
];
/// Marks a skill file written by `jsonr skill --init`. `jsonr update`
/// rewrites only the files that still have it.
const MARKER: &str = "<!-- Generated by `jsonr skill --init`";

pub fn matches(args: &Object) -> bool {
    is_command(args, "skill")
}

pub fn execute(args: &Object) -> Result<(), String> {
    if args.is_truthy("init") {
        return create_skill();
    }
    if args.is_truthy("refresh") {
        refresh();
        return Ok(());
    }
    logger::print_line(AGENT_INSTRUCTIONS);
    help::execute();
    Ok(())
}

/// The skill with the marker line right after the front matter, where
/// agents still read the front matter.
fn generated_skill() -> String {
    let marker = format!(
        "{MARKER}. `jsonr update` rewrites this file; delete this line to keep your own changes. -->\n"
    );
    match SKILL_CONTENT
        .strip_prefix("---\n")
        .and_then(|rest| rest.find("\n---\n"))
    {
        Some(end) => {
            let split = "---\n".len() + end + "\n---\n".len();
            format!(
                "{}{marker}{}",
                &SKILL_CONTENT[..split],
                &SKILL_CONTENT[split..]
            )
        }
        None => format!("{marker}{SKILL_CONTENT}"),
    }
}

fn is_generated(text: &str) -> bool {
    text.lines().any(|line| line.starts_with(MARKER))
}

fn skill_files(root: &Path) -> Vec<PathBuf> {
    SKILL_TARGETS
        .iter()
        .map(|(dir, _)| root.join(dir).join(SKILL_NAME).join("SKILL.md"))
        .collect()
}

/// The git root around the current directory (searched up to the home
/// directory).
fn git_root(start: &Path, home: Option<&Path>) -> Option<PathBuf> {
    let mut dir = start;
    loop {
        if dir.join(".git").exists() {
            return Some(dir.to_path_buf());
        }
        if Some(dir) == home {
            return None;
        }
        dir = dir.parent()?;
    }
}

struct SkillRoot {
    dir: PathBuf,
    reason: &'static str,
    global: bool,
}

/// Inside a git repository (searched from cwd up to the home directory): the
/// git root. Outside a repository: the home directory, where Claude Code,
/// Codex, Cursor and other agents read user-level skills.
fn find_skill_root() -> Result<SkillRoot, String> {
    let home = home_dir().map(PathBuf::from);
    let start = std::env::current_dir().unwrap_or_default();
    if let Some(dir) = git_root(&start, home.as_deref()) {
        return Ok(SkillRoot {
            dir,
            reason: "git root",
            global: false,
        });
    }
    let home =
        home.ok_or("Not in a git repository and the home directory is unknown (set HOME).")?;
    Ok(SkillRoot {
        dir: home,
        reason: "not in a git repository",
        global: true,
    })
}

fn write_skill(file: &Path, content: &str) -> Result<(), String> {
    if let Some(parent) = file.parent() {
        std::fs::create_dir_all(parent).map_err(|err| format!("{}: {err}", parent.display()))?;
    }
    std::fs::write(file, content).map_err(|err| format!("{}: {err}", file.display()))
}

/// `jsonr skill --init`: writes the skill, replacing the files when they
/// exist.
fn create_skill() -> Result<(), String> {
    let root = find_skill_root()?;
    let content = generated_skill();
    let mut written = Vec::new();
    for ((dir, read_by), file) in SKILL_TARGETS.iter().zip(skill_files(&root.dir)) {
        let action = if file.exists() { "Updated" } else { "Created" };
        write_skill(&file, &content)?;
        let path = Path::new(dir).join(SKILL_NAME).join("SKILL.md");
        written.push(format!("{action} {}  ({read_by})", path.display()));
    }

    if root.global {
        logger::info(format!(
            "Not in a git repository - installing for all projects in {}",
            root.dir.display()
        ));
    } else {
        logger::info(format!(
            "Project root: {} ({})",
            root.dir.display(),
            root.reason
        ));
    }
    for line in &written {
        logger::info(line);
    }
    logger::info("");
    logger::info("Try: /jsonr send the create-user request against prod");
    Ok(())
}

/// The skill files under `root` that still have the marker.
fn generated_files(root: &Path) -> Vec<PathBuf> {
    skill_files(root)
        .into_iter()
        .filter(|file| std::fs::read_to_string(file).is_ok_and(|text| is_generated(&text)))
        .collect()
}

/// Rewrites the skills that `jsonr skill --init` wrote, when they still have
/// the marker: the ones at the git root of the current directory, else (no
/// repository, or no generated skill in it) the ones in the home directory.
/// Prints the files it changed. Run by `jsonr update` with the new binary
/// (`jsonr skill --refresh`), so the new skill text is written.
pub fn refresh() {
    let home = home_dir().map(PathBuf::from);
    let cwd = std::env::current_dir().unwrap_or_default();
    let files = git_root(&cwd, home.as_deref())
        .map(|root| generated_files(&root))
        .filter(|files| !files.is_empty())
        .or_else(|| home.as_deref().map(generated_files))
        .unwrap_or_default();

    let content = generated_skill();
    let mut updated = Vec::new();
    for file in files {
        if std::fs::read_to_string(&file).is_ok_and(|text| text == content) {
            continue;
        }
        match std::fs::write(&file, &content) {
            Ok(()) => updated.push(file),
            Err(err) => logger::error(format!(
                "ERROR: Failed to update the skill {}: {err}",
                file.display()
            )),
        }
    }
    if !updated.is_empty() {
        logger::info("Updated skills:");
        for file in &updated {
            logger::info(format!("  {}", file.display()));
        }
    }
}
